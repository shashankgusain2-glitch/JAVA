package Kunal.Pattern;

public class P1 {
    static void main() {
        Solution(5);
    }

    static void Solution(int n){
        for (int i = 0; i < n; i++) {
            for(int j=0; j<n; j++){
                System.out.print("*");
            }
            System.out.println();

        }

    }
}

